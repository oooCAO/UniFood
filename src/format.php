<?php
/**
 * Общие функции форматирования данных для вывода на страницы сайта.
 *
 * Файл вынесен отдельно, потому что цены показывают почти все разделы
 * (каталог, корзина, оформление заказа, история заказов, админка, статистика).
 * Если формат задавать в каждом файле отдельно, они быстро разъедутся:
 * где-то останется «₽», где-то появится точка вместо запятой. Одна общая
 * функция гарантирует, что по всему сайту цена выглядит одинаково.
 */

/**
 * Форматирует цену для вывода на страницы сайта.
 *
 * Формат: два знака после запятой, разделитель дробной части — запятая,
 * разделитель тысяч — обычный пробел. Функция используется только для
 * вывода: в базе и в total_price цены остаются числами.
 *
 * @param float $price Цена в белорусских рублях.
 * @return string Цена вида «4,50 BYN».
 */
function formatPrice(float $price): string
{
    return number_format($price, 2, ',', ' ') . ' BYN';
}
